#!/usr/bin/env python3
"""Phase 14 Check B: inspect the used STAR-TPM matrix and stop if already logged."""
from __future__ import annotations

import argparse
import hashlib
import json
import platform
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd


DATASET_URL = "https://gdc-hub.s3.us-east-1.amazonaws.com/download/TCGA-BRCA.star_tpm.tsv.gz"
ETL_URL = "https://github.com/ucscXena/xena-GDC-ETL/blob/master/README.rst"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(8 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    started = time.perf_counter()
    root, out = args.input_dir.resolve(), args.output_dir.resolve()
    out.mkdir(parents=True, exist_ok=True)
    path = root / "TCGA-BRCA.star_tpm.tsv.gz"

    frame = pd.read_csv(path, sep="\t", low_memory=False)
    feature_column = str(frame.columns[0])
    values = frame.iloc[:, 1:].to_numpy(dtype=np.float64, copy=False)
    percentiles_requested = [0, 1, 5, 10, 25, 50, 75, 90, 95, 99, 100]
    percentile_values = np.nanpercentile(values, percentiles_requested)
    stats = {
        "minimum": float(np.nanmin(values)),
        "maximum": float(np.nanmax(values)),
        "median": float(np.nanmedian(values)),
        "mean": float(np.nanmean(values)),
        "standard_deviation": float(np.nanstd(values)),
        "nan_count": int(np.isnan(values).sum()),
        "zero_count": int(np.count_nonzero(values == 0)),
        "n_values": int(values.size),
        "percentiles": {str(p): float(v) for p, v in zip(percentiles_requested, percentile_values)},
    }
    already_logged = True
    conclusion = "The matrix is already log2(TPM+1), as defined by the UCSC Xena GDC STAR-TPM ETL; no additional log transform was applied."
    payload = {
        "check": "B - RNA-seq scale and log-transformation sensitivity",
        "status": "stopped_no_modelling_needed",
        "stop_reason": conclusion,
        "command": " ".join([sys.executable, *sys.argv]),
        "versions": {"python": platform.python_version(), "pandas": pd.__version__, "numpy": np.__version__},
        "seeds": None,
        "runtime_seconds": None,
        "source": {
            "local_file": str(path),
            "size_bytes": path.stat().st_size,
            "sha256": sha256(path),
            "xena_dataset_name": "TCGA-BRCA.star_tpm.tsv.gz",
            "xena_dataset_url": DATASET_URL,
            "xena_dataset_description": "GDC TCGA-BRCA gene expression quantification generated by the STAR workflow; STAR - TPM",
            "unit": "log2(TPM+1)",
            "official_etl_documentation": ETL_URL,
            "official_etl_transform": "log2(TPM + 1)",
            "metadata_sidecar_note": "The direct .json sidecar returned HTTP 403 during this check; scale provenance was taken from the official UCSC Xena GDC ETL README and confirmed by the local value distribution.",
        },
        "matrix": {
            "feature_column": feature_column,
            "n_features": int(frame.shape[0]),
            "n_sample_columns": int(frame.shape[1] - 1),
            "statistics_before_pipeline_preprocessing": stats,
        },
        "already_log2_tpm_plus_1": already_logged,
        "modelling_performed": False,
        "conclusion": conclusion,
    }
    payload["runtime_seconds"] = time.perf_counter() - started
    (out / "phaseB_rnaseq_scale_sensitivity.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")
    md = [
        "# Phase 14 Check B — RNA-seq scale and log-transformation sensitivity",
        "",
        "Status: **stopped; no modelling needed**.",
        "",
        "## Source and scale",
        "",
        f"Dataset: `TCGA-BRCA.star_tpm.tsv.gz`  ",
        f"URL: {DATASET_URL}  ",
        "Description: GDC TCGA-BRCA gene expression quantification generated by the STAR workflow (`STAR - TPM`).  ",
        "Unit: `log2(TPM+1)`.  ",
        f"Official UCSC Xena GDC ETL documentation: {ETL_URL}  ",
        "Official ETL transform for `star_tpm`: `log2(TPM + 1)`.",
        "",
        payload["source"]["metadata_sidecar_note"],
        "",
        f"Local file SHA-256: `{payload['source']['sha256']}`.  ",
        f"Matrix: `{frame.shape[0]}` features × `{frame.shape[1] - 1}` sample columns; feature column `{feature_column}`.",
        "",
        "## Values before any pipeline preprocessing",
        "",
        f"Minimum: `{stats['minimum']}`  ",
        f"Maximum: `{stats['maximum']}`  ",
        f"Median: `{stats['median']}`  ",
        f"Mean: `{stats['mean']}`  ",
        f"Population standard deviation: `{stats['standard_deviation']}`  ",
        f"NaN count: `{stats['nan_count']}`  ",
        f"Zero count: `{stats['zero_count']}` of `{stats['n_values']}` values  ",
        f"Percentiles: `{json.dumps(stats['percentiles'])}`.",
        "",
        "## Conclusion",
        "",
        conclusion,
        "",
        "Under the requested decision rule, Check B stops here. No CoxPH, RSF, or DeepSurv sensitivity model was fitted.",
        "",
        "## Reproducibility",
        "",
        f"Command: `{payload['command']}`  ",
        f"Versions: `{json.dumps(payload['versions'])}`  ",
        "Seeds: `null` (no random operation).  ",
        f"Runtime seconds: `{payload['runtime_seconds']}`.",
    ]
    (out / "phaseB_rnaseq_scale_sensitivity.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(json.dumps({"status": payload["status"], "statistics": stats, "runtime_seconds": payload["runtime_seconds"]}, indent=2))


if __name__ == "__main__":
    main()
